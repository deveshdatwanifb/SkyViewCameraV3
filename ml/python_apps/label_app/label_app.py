def parse_s3_uri(s3_uri):
    s3_uri = s3_uri.strip()
    if s3_uri.lower().startswith('s3://'):
        s3_uri = s3_uri[5:]
    parts = s3_uri.split('/', 1)
    bucket = parts[0]
    prefix = (parts[1].strip() if len(parts) > 1 else '').strip('/')
    return bucket, prefix


def local_dir_for_uri(bucket, prefix):
    """Derive the local dataset folder (label_app/datasets/<bucket>[_<prefix>])."""
    name = bucket + ('_' + prefix.replace('/', '_') if prefix else '')
    safe = "".join(c if (c.isalnum() or c in '-_.') else '_' for c in name)
    return os.path.join(DATASETS_DIR, safe)


def s3_key_for(prefix, rel):
    rel = rel.replace('\\', '/')
    return f"{prefix}/{rel}" if prefix else rel


def list_s3_objects(s3_client, bucket, prefix):
    """Return {relative_path: {Key, ETag}} for every object under the prefix."""
    objs = {}
    paginator = s3_client.get_paginator('list_objects_v2')
    kwargs = {'Bucket': bucket}
    if prefix:
        kwargs['Prefix'] = prefix + '/'
    for page in paginator.paginate(**kwargs):
        for obj in page.get('Contents', []):
            key = obj['Key']
            if key.endswith('/'):
                continue
            rel = key[len(prefix) + 1:] if prefix else key
            if rel:
                objs[rel] = {"Key": key, "ETag": obj.get('ETag')}
    return objs


def list_local_files(local_dir):
    """Return {relative_path: absolute_path} for every (non-hidden) file."""
    out = {}
    for root, _dirs, files in os.walk(local_dir):
        for fn in files:
            if fn.startswith('.'):
                continue
            full = os.path.join(root, fn)
            rel = os.path.relpath(full, local_dir).replace('\\', '/')
            out[rel] = full
    return out


def pull_bucket(s3_client, bucket, prefix, local_dir):
    """Download every object under the prefix into local_dir (preserving layout)."""
    os.makedirs(local_dir, exist_ok=True)
    objs = list_s3_objects(s3_client, bucket, prefix)
    for rel, info in objs.items():
        dest = os.path.join(local_dir, rel)
        os.makedirs(os.path.dirname(dest), exist_ok=True)
        s3_client.download_file(bucket, info['Key'], dest)
    if not os.path.exists(os.path.join(local_dir, DATA_YAML)):
        write_data_yaml(local_dir)
    return len(objs)


def push_local(s3_client, bucket, prefix, local_dir, do_delete):
    """Upload changed local files; optionally delete S3 objects missing locally."""
    local_files = list_local_files(local_dir)
    s3_objs = list_s3_objects(s3_client, bucket, prefix)

    uploaded, skipped = 0, 0
    for rel, full in local_files.items():
        existing = s3_objs.get(rel)
        if existing and existing.get('ETag') == calculate_local_file_md5(full):
            skipped += 1
            continue
        s3_client.upload_file(full, bucket, s3_key_for(prefix, rel))
        uploaded += 1

    to_delete = [rel for rel in s3_objs if rel not in local_files]
    deleted = 0
    if do_delete:
        for rel in to_delete:
            s3_client.delete_object(Bucket=bucket, Key=s3_objs[rel]['Key'])
            deleted += 1
    return {
        "uploaded": uploaded, "skipped": skipped, "to_delete": to_delete,
        "deleted": deleted, "local_count": len(local_files), "cloud_count": len(s3_objs),
    }


