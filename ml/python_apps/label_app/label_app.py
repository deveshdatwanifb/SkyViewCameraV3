import os
import json
import platform
import subprocess
import hashlib
from datetime import datetime
from flask import Flask, render_template, jsonify, request, send_from_directory
import tkinter as tk
from tkinter import filedialog
import boto3
from botocore.exceptions import NoCredentialsError, ClientError
from PIL import Image

app = Flask(__name__, static_folder='.', static_url_path='')

APP_DIR = os.path.dirname(os.path.abspath(__file__))
DATASETS_DIR = os.path.join(APP_DIR, 'datasets')

# Single object-detection class (many instances per frame are fine).
CLASS_NAMES = ["airplane"]

# Ordered keypoints for the pose model. The position in this list IS the keypoint
# index written into the YOLO label file (YOLO stores slots, not names).
KP_ORDER = [
    "nose", "left_wing_tip", "right_wing_tip", "tail_top_corner",
    "left_landing_gear", "right_landing_gear", "nose_gear"
]
NUM_KP = len(KP_ORDER)
# Left/right swap map for horizontal-flip augmentation (Ultralytics flip_idx).
KP_FLIP_IDX = [0, 2, 1, 3, 5, 4, 6]

IMAGE_EXTS = ('.jpg', '.jpeg', '.png', '.bmp', '.webp')
DATA_YAML = 'data.yaml'
METADATA_FILE = 'metadata.json'  # holds per-image tags + save timestamps (not labels)


def open_native_folder_browser():
    if platform.system() == "Darwin":
        try:
            cmd = ['osascript', '-e', 'POSIX path of (choose folder with prompt "Select Workspace Folder:")']
            return subprocess.check_output(cmd, stderr=subprocess.DEVNULL).decode('utf-8').strip()
        except subprocess.CalledProcessError: return None
    else:
        root = tk.Tk()
        root.withdraw()
        root.attributes('-topmost', True)
        path = filedialog.askdirectory()
        root.destroy()
        return path


