def label_path_for(workspace, image_filename):
    return os.path.join(workspace, os.path.splitext(image_filename)[0] + '.txt')


def write_data_yaml(workspace):
    """Write the Ultralytics dataset descriptor describing classes + keypoints."""
    lines = [
        "# FyveBy Aircraft Keypoint Dataset (YOLO pose format)",
        "# Auto-generated by label_app.py -- edit class/keypoint config there.",
        "path: .",
        "train: .",
        "val: .",
        "",
        "names:",
    ]
    lines += [f"  {i}: {name}" for i, name in enumerate(CLASS_NAMES)]
    lines += [
        "",
        f"kpt_shape: [{NUM_KP}, 3]",
        f"flip_idx: {KP_FLIP_IDX}",
        "# Keypoint slot order (YOLO uses index position only, names are for reference):",
        "# " + ", ".join(f"{i}:{name}" for i, name in enumerate(KP_ORDER)),
    ]
    with open(os.path.join(workspace, DATA_YAML), 'w') as f:
        f.write("\n".join(lines) + "\n")


def load_metadata(workspace):
    path = os.path.join(workspace, METADATA_FILE)
    if os.path.exists(path):
        try:
            with open(path) as f: return json.load(f)
        except Exception: return {}
    return {}


def save_metadata(workspace, meta):
    with open(os.path.join(workspace, METADATA_FILE), 'w') as f:
        json.dump(meta, f, indent=2)


def _clamp01(v):
    return min(1.0, max(0.0, v))


def commit_save_to_yolo(workspace, filename, bboxes, keypoints, tags, img_w, img_h):
    """Write one YOLO pose label file (<image>.txt). One line per instance:
    `cls cx cy w h px1 py1 v1 ... px7 py7 v7`, all box/point coords normalized.
    Keypoints are assigned to whichever box contains them; absent slots are zeroed.
    Tags + timestamp are kept in metadata.json (YOLO has no slot for them)."""
    timestamp = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    img_w = float(img_w) or 1.0
    img_h = float(img_h) or 1.0

    lines = []
    for box in bboxes:
        x1, x2 = min(box['x1'], box['x2']), max(box['x1'], box['x2'])
        y1, y2 = min(box['y1'], box['y2']), max(box['y1'], box['y2'])
        cls = CLASS_NAMES.index(box['label']) if box.get('label') in CLASS_NAMES else 0
        parts = [
            str(cls),
            f"{_clamp01((x1 + x2) / 2 / img_w):.6f}",
            f"{_clamp01((y1 + y2) / 2 / img_h):.6f}",
            f"{_clamp01((x2 - x1) / img_w):.6f}",
            f"{_clamp01((y2 - y1) / img_h):.6f}",
        ]
        slots = [(0.0, 0.0, 0)] * NUM_KP
        for kp in keypoints:
            if x1 <= kp['x'] <= x2 and y1 <= kp['y'] <= y2 and kp['label'] in KP_ORDER:
                idx = KP_ORDER.index(kp['label'])
                slots[idx] = (_clamp01(kp['x'] / img_w), _clamp01(kp['y'] / img_h), int(kp.get('visibility', 2)))
        for kx, ky, kv in slots:
            parts += [f"{kx:.6f}", f"{ky:.6f}", str(kv)]
        lines.append(" ".join(parts))

    with open(label_path_for(workspace, filename), 'w') as f:
        f.write("\n".join(lines) + ("\n" if lines else ""))

    meta = load_metadata(workspace)
    meta[filename] = {"tags": tags, "date": timestamp}
    save_metadata(workspace, meta)

    if not os.path.exists(os.path.join(workspace, DATA_YAML)):
        write_data_yaml(workspace)
    return timestamp


def parse_yolo_label_file(txt_path, img_w, img_h):
    """Parse a YOLO pose label file back into pixel-space app structures."""
    bboxes, keypoints = [], []
    if not os.path.exists(txt_path):
        return bboxes, keypoints
    with open(txt_path) as f:
        for raw in f:
            parts = raw.strip().split()
            if not parts:
                continue
            try:
                vals = [float(p) for p in parts]
            except ValueError:
                continue
            cls = int(vals[0])
            cx, cy = vals[1] * img_w, vals[2] * img_h
            bw, bh = vals[3] * img_w, vals[4] * img_h
            label = CLASS_NAMES[cls] if 0 <= cls < len(CLASS_NAMES) else CLASS_NAMES[0]
            bboxes.append({"x1": cx - bw / 2, "y1": cy - bh / 2,
                           "x2": cx + bw / 2, "y2": cy + bh / 2, "label": label})
            kp_vals = vals[5:]
            for i in range(NUM_KP):
                base = i * 3
                if base + 2 < len(kp_vals):
                    kx, ky, kv = kp_vals[base], kp_vals[base + 1], int(kp_vals[base + 2])
                    if kv > 0:
                        keypoints.append({"x": kx * img_w, "y": ky * img_h,
                                          "label": KP_ORDER[i], "visibility": kv})
    return bboxes, keypoints


def load_yolo_annotations(workspace):
    """Build the in-app annotation store from per-image YOLO .txt files."""
    meta = load_metadata(workspace)
    app_store = {}
    images = [f for f in os.listdir(workspace) if f.lower().endswith(IMAGE_EXTS)]
    for fname in images:
        bboxes, keypoints = [], []
        txt = label_path_for(workspace, fname)
        if os.path.exists(txt):
            try:
                with Image.open(os.path.join(workspace, fname)) as im:
                    w, h = im.size
                bboxes, keypoints = parse_yolo_label_file(txt, w, h)
            except Exception:
                pass
        m = meta.get(fname, {})
        app_store[fname] = {
            "bboxes": bboxes, "keypoints": keypoints,
            "tags": m.get("tags", []), "date": m.get("date", "Not annotated yet")
        }
    return app_store


def calculate_local_file_md5(file_path):
    hasher = hashlib.md5()
    with open(file_path, 'rb') as f:
        for chunk in iter(lambda: f.read(4096), b''): hasher.update(chunk)
    return f'"{hasher.hexdigest()}"'


