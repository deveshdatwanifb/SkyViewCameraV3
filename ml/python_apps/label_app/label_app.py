@app.route('/')
def home():
    return render_template('index.html')


@app.route('/select_folder', methods=['POST'])
def select_folder():
    target_path = open_native_folder_browser()
    if not target_path: return jsonify({"status": "cancelled"})
    image_list = [f for f in os.listdir(target_path) if f.lower().endswith(IMAGE_EXTS)]
    return jsonify({"folder": target_path, "images": image_list,
                    "annotations": load_yolo_annotations(target_path)})


@app.route('/image/<path:filename>')
def serve_image(filename):
    workspace = request.args.get('workspace')
    if not workspace or not os.path.exists(workspace): return "Missing space parameter query profile", 400
    return send_from_directory(workspace, filename)


@app.route('/save', methods=['POST'])
def save():
    payload = request.json
    workspace = payload.get('workspace')
    if not workspace: return jsonify({"status": "error", "message": "Missing active workspace token."}), 400
    try:
        timestamp = commit_save_to_yolo(
            workspace, payload.get('filename'), payload.get('bboxes', []),
            payload.get('keypoints', []), payload.get('tags', []),
            payload.get('image_width', 1920), payload.get('image_height', 1080)
        )
        return jsonify({"status": "success", "date": timestamp})
    except Exception as e: return jsonify({"status": "error", "message": str(e)}), 500


@app.route('/delete_image', methods=['POST'])
def delete_image():
    payload = request.json
    workspace = payload.get('workspace')
    filename = payload.get('filename')
    target = os.path.join(workspace, filename)
    if os.path.exists(target): os.remove(target)
    txt = label_path_for(workspace, filename)
    if os.path.exists(txt): os.remove(txt)
    meta = load_metadata(workspace)
    if filename in meta:
        del meta[filename]
        save_metadata(workspace, meta)
    return jsonify({"status": "success"})


@app.route('/transform_image', methods=['POST'])
def transform_image():
    payload = request.json
    workspace = payload.get('workspace')
    filename = payload.get('filename')
    action = payload.get('action')
    tags = payload.get('tags', [])
    incoming_bboxes = payload.get('bboxes', [])
    incoming_keypoints = payload.get('keypoints', [])

    img_path = os.path.join(workspace, filename)
    try:
        with Image.open(img_path) as img:
            orig_w, orig_h = img.size
            if action == 'crop':
                coords = payload.get('coords')
                x1, y1 = max(0, int(coords[0])), max(0, int(coords[1]))
                x2, y2 = min(orig_w, int(coords[2])), min(orig_h, int(coords[3]))
                crop_w, crop_h = x2 - x1, y2 - y1

                for box in incoming_bboxes:
                    bx1, by1, bx2, by2 = box['x1'], box['y1'], box['x2'], box['y2']
                    if not (bx2 <= x1 or bx1 >= x2 or by2 <= y1 or by1 >= y2) and not (bx1 >= x1 and bx2 <= x2 and by1 >= y1 and by2 <= y2):
                        return jsonify({"status": "error", "message": f"Crop Rejected: This custom selection slice splits through the instance box labeled '{box['label']}'."}), 400

                img.crop((x1, y1, x2, y2)).save(img_path)
                transformed_bboxes = [{"x1": max(0, b['x1'] - x1), "y1": max(0, b['y1'] - y1), "x2": min(crop_w, b['x2'] - x1), "y2": min(crop_h, b['y2'] - y1), "label": b['label']} for b in incoming_bboxes if min(crop_w, b['x2'] - x1) > max(0, b['x1'] - x1)]
                transformed_keypoints = [{"x": k['x'] - x1, "y": k['y'] - y1, "label": k['label'], "visibility": k['visibility']} for k in incoming_keypoints if 0 <= (k['x'] - x1) <= crop_w and 0 <= (k['y'] - y1) <= crop_h]

                timestamp = commit_save_to_yolo(workspace, filename, transformed_bboxes, transformed_keypoints, tags, crop_w, crop_h)
                return jsonify({"status": "success", "bboxes": transformed_bboxes, "keypoints": transformed_keypoints, "date": timestamp})

            elif action == 'resize':
                target_w = int(payload.get('width'))
                ratio = target_w / orig_w
                target_h = int(orig_h * ratio)
                img.resize((target_w, target_h), Image.Resampling.LANCZOS).save(img_path)
                transformed_bboxes = [{"x1": b['x1']*ratio, "y1": b['y1']*ratio, "x2": b['x2']*ratio, "y2": b['y2']*ratio, "label": b['label']} for b in incoming_bboxes]
                transformed_keypoints = [{"x": k['x']*ratio, "y": k['y']*ratio, "label": k['label'], "visibility": k['visibility']} for k in incoming_keypoints]

                timestamp = commit_save_to_yolo(workspace, filename, transformed_bboxes, transformed_keypoints, tags, target_w, target_h)
                return jsonify({"status": "success", "bboxes": transformed_bboxes, "keypoints": transformed_keypoints, "date": timestamp})
    except Exception as e: return jsonify({"status": "error", "message": str(e)}), 500


@app.route('/sync_s3', methods=['POST'])
def sync_s3():
    """S3 sync. If the local dataset dir for this URI is missing/empty -> PULL the
    whole bucket into label_app/datasets/<bucket>. If it already exists -> PUSH local
    up to the cloud. When the bucket holds files the local folder no longer has, we
    do NOT delete on the first pass: we return a warning comparing file counts and
    only delete from S3 (local is source of truth) once the user re-confirms."""
    payload = request.json
    s3_uri = payload.get('s3_uri', '').strip()
    confirm_delete = bool(payload.get('confirm_delete', False))

    if not s3_uri:
        return jsonify({"status": "error", "message": "Missing S3 URI parameter field."}), 400
    bucket, prefix = parse_s3_uri(s3_uri)
    if not bucket:
        return jsonify({"status": "error", "message": "Could not parse a bucket name from the S3 URI."}), 400

    local_dir = local_dir_for_uri(bucket, prefix)
    pretty_uri = f"s3://{bucket}/{prefix}" if prefix else f"s3://{bucket}"

    try:
        s3_client = boto3.client('s3')

        # CASE A -- nothing local yet: pull the bucket down and open it.
        if not os.path.isdir(local_dir) or not os.listdir(local_dir):
            count = pull_bucket(s3_client, bucket, prefix, local_dir)
            images = [f for f in os.listdir(local_dir) if f.lower().endswith(IMAGE_EXTS)]
            return jsonify({
                "status": "pulled", "folder": local_dir, "images": images,
                "annotations": load_yolo_annotations(local_dir),
                "message": f"Pulled {count} object(s) from {pretty_uri} into:\n{local_dir}"
            })

        # CASE B -- local dir exists: push local up to the cloud.
        result = push_local(s3_client, bucket, prefix, local_dir, confirm_delete)

        if result["to_delete"] and not confirm_delete:
            n = len(result["to_delete"])
            return jsonify({
                "status": "confirm_delete",
                "local_count": result["local_count"],
                "cloud_count": result["cloud_count"],
                "delete_count": n,
                "message": (
                    "DELETE WARNING -- file counts differ between local and S3.\n\n"
                    f"Local folder : {result['local_count']} files\n"
                    f"S3 bucket    : {result['cloud_count']} files\n\n"
                    f"Uploaded {result['uploaded']} changed file(s).\n"
                    f"{n} file(s) exist in S3 but NOT locally.\n\n"
                    f"Confirm to DELETE those {n} file(s) from {pretty_uri} so the bucket "
                    "mirrors your local folder. This is IRREVERSIBLE."
                )
            })

        msg = f"Sync complete.\nUploaded {result['uploaded']}, skipped {result['skipped']} unchanged."
        if result["deleted"]:
            msg += f"\nDeleted {result['deleted']} file(s) from S3 to mirror local."
        cloud_after = result["cloud_count"] - result["deleted"]
        msg += f"\n\nLocal: {result['local_count']} files  |  S3: {cloud_after} files"
        return jsonify({"status": "success", "message": msg})

    except NoCredentialsError:
        return jsonify({"status": "error", "message": "AWS credentials not found. Run `aws configure` first."}), 500
    except Exception as e:
        return jsonify({"status": "error", "message": str(e)}), 500


